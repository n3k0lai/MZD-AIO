//! Plan → bundle files. Pure and deterministic.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::catalog::{BackupPolicy, RUNTIME_SH, StepOp};
use crate::config::{Action, Mode};
use crate::manifest::{self, Manifest};
use crate::plan::{Plan, payload_path};

/// Every file of a USB bundle, keyed by path relative to the stick root.
#[derive(Debug)]
pub struct Bundle {
    pub files: BTreeMap<String, Vec<u8>>,
    pub manifest: Manifest,
}

/// Single-quote a string for POSIX sh.
pub fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

fn call(out: &mut String, func: &str, args: &[&str]) {
    out.push_str("  ");
    out.push_str(func);
    for a in args {
        out.push(' ');
        out.push_str(&sh_quote(a));
    }
    out.push('\n');
}

fn emit(out: &mut String, tweak: &str, step: &StepOp) {
    let payload = payload_path(tweak, step).unwrap_or_default();
    match step {
        StepOp::RequireFile { path } => call(out, "require_file", &[path]),
        StepOp::RequireLiteral {
            path,
            literal,
            count,
            applied,
            hint,
        } => {
            let want = count.map_or("any".to_string(), |c| c.to_string());
            call(
                out,
                "require_literal",
                &[
                    path,
                    literal,
                    &want,
                    applied.as_deref().unwrap_or(""),
                    hint.as_deref().unwrap_or(""),
                ],
            );
        }
        StepOp::RequireBackup { path } => call(out, "require_backup", &[path]),
        StepOp::Backup { .. } => {} // all backups run together before the first write
        StepOp::AppendBlock { path, block, .. } => {
            call(out, "append_block", &[path, block, &payload])
        }
        StepOp::RemoveBlock { path, block } => call(out, "remove_block", &[path, block]),
        StepOp::ReplaceLiteral {
            path,
            find,
            replace,
        } => call(out, "replace_literal", &[path, find, replace]),
        StepOp::InstallFile { path, .. } => call(out, "install_file", &[path, &payload]),
        StepOp::Restore { path } => call(out, "restore_file", &[path]),
        StepOp::Exec { argv } => {
            let args: Vec<&str> = argv.iter().map(String::as_str).collect();
            call(out, "run_stock", &args);
        }
    }
}

pub fn run_sh(plan: &Plan) -> String {
    let (strategy, dir) = match &plan.profile.backup {
        BackupPolicy::Sibling => ("sibling", ""),
        BackupPolicy::Dir { dir } => ("dir", dir.as_str()),
    };
    let mode = match plan.config.mode {
        Mode::Check => "check",
        Mode::Apply => "apply",
    };
    let mut s = String::new();
    let _ = writeln!(
        s,
        "#!/bin/sh\n\
         # Generated by {} {}. Do not edit; regenerate from the bundle config.\n\
         # Install logic derived from MZD-AIO-TI by Trevor G Martin (Trevelopment) and\n\
         # contributors, GPL-3.0. See manifest.json for exactly what this does.\n",
        crate::GENERATOR_NAME,
        crate::GENERATOR_VERSION
    );
    for (k, v) in [
        ("MODE", mode),
        ("REBOOT", if plan.config.reboot { "1" } else { "0" }),
        ("EXPECT_VER", &plan.firmware.base()),
        ("EXPECT_PATCH", &plan.firmware.letter),
        ("BACKUP_STRATEGY", strategy),
        ("BACKUP_DIR", dir),
    ] {
        let _ = writeln!(s, "{k}={}", sh_quote(v));
    }
    s.push('\n');
    s.push_str(RUNTIME_SH.trim_end());
    s.push_str("\n\nmain() {\n");
    let ids: Vec<String> = plan
        .tweaks
        .iter()
        .map(|t| format!("{}:{:?}", t.id, t.action).to_lowercase())
        .collect();
    call(
        &mut s,
        "log",
        &[&format!(
            "=== mzd-tweaks {} | mode {mode} | {}",
            crate::GENERATOR_VERSION,
            ids.join(" ")
        )],
    );
    s.push_str("  [ \"$SIM\" = 1 ] || mount -o rw,remount \"$MYDIR\"\n  check_fw\n");
    call(&mut s, "log", &["--- preflight"]);
    for step in &plan.preflight {
        emit(&mut s, "", step);
    }
    for need in &plan.space {
        let mut expr = need.payload_bytes.to_string();
        for b in &need.backups {
            let _ = write!(expr, " + $(backup_cost {})", sh_quote(b));
        }
        let _ = writeln!(
            s,
            "  need_space {} \"$(({expr}))\" {}",
            sh_quote(need.partition.mount()),
            need.reserve_kib
        );
    }
    s.push_str(
        "  [ \"$FAILED\" = 0 ] || die \"preflight failed; nothing was changed\"\n\
         \x20 if [ \"$MODE\" != apply ]; then\n\
         \x20   log \"check passed; nothing was changed (mode check)\"\n\
         \x20   notify \"MZD-TWEAKS CHECK PASSED. NOTHING WAS CHANGED.\"\n\
         \x20   disarm\n\
         \x20   return 0\n\
         \x20 fi\n\
         \x20 prepare_hw\n",
    );
    call(&mut s, "log", &["--- backups"]);
    for b in &plan.backups {
        call(&mut s, "backup_file", &[b]);
    }
    for t in &plan.tweaks {
        let action = if t.action == Action::Install {
            "install"
        } else {
            "uninstall"
        };
        call(&mut s, "log", &[&format!("--- {} ({action})", t.id)]);
        for step in t.steps.iter().filter(|st| !st.is_preflight()) {
            emit(&mut s, &t.id, step);
        }
    }
    s.push_str(
        "  log \"done\"\n\
         \x20 disarm\n\
         \x20 notify \"MZD-TWEAKS APPLIED. YOU CAN REMOVE THE USB DRIVE.\"\n\
         \x20 if [ \"$REBOOT\" = 1 ] && [ \"$SIM\" != 1 ]; then sleep 5; reboot; fi\n\
         }\n\nmain \"$@\"\n",
    );
    s
}

fn readme(m: &Manifest) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "mzd-tweaks bundle for firmware {} ({})",
        m.firmware.requested, m.firmware.profile_label
    );
    let _ = writeln!(
        s,
        "Mode: {:?}. Generated by {} {}.\n",
        m.mode, m.generator.name, m.generator.version
    );
    for t in &m.tweaks {
        let _ = writeln!(s, "  {:?} {} - {}", t.action, t.id, t.title);
    }
    s.push_str(
        "\nCopy every file to the root of a FAT32 USB stick. A CMU with the autorun hook runs\n\
         run.sh on boot, writes mzd-tweaks.log here, and renames run.sh to run.sh.done.\n\
         Check mode changes nothing. Backups are copied to backups/ on this stick.\n",
    );
    if !m.warnings.is_empty() {
        s.push_str("\nWarnings:\n");
        for w in &m.warnings {
            let _ = writeln!(s, "  - {w}");
        }
    }
    s
}

pub fn render(plan: &Plan) -> Bundle {
    let manifest = manifest::build(plan);
    let mut files = plan.payloads.clone();
    files.insert("run.sh".into(), run_sh(plan).into_bytes());
    let mut json = serde_json::to_string_pretty(&manifest).expect("manifest serializes");
    json.push('\n');
    files.insert("manifest.json".into(), json.into_bytes());
    files.insert("README.txt".into(), readme(&manifest).into_bytes());
    Bundle { files, manifest }
}
